export function getNextSuggestion(completedIds, pattern) {
  const suggestions = PATTERN_SUGGESTIONS[pattern] || PATTERN_SUGGESTIONS.reactor;
  const suggested = suggestions.find(id => !completedIds.includes(id));
  if (suggested) return MODULES.find(m => m.id === suggested);
  const household = MODULES.filter(m => m.layer === 'household' && !completedIds.includes(m.id));
  return household[0] || null;
}